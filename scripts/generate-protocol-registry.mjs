import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(root, "apps/studio/src/domain/protocol/inventory.json");
const source = JSON.parse(readFileSync(sourcePath, "utf8"));
const requiredProfiles = [
  "android",
  "ios",
  "tdesktop",
  "macos",
  "weba",
  "webk",
];

function ownerFor(name) {
  if (
    /(accelerometer|gyroscope|orientation|biometry|haptic|vibration)/u.test(
      name,
    )
  )
    return "04e";
  if (/(device_storage|secure_storage|cloud_storage)/u.test(name)) return "04f";
  if (/(location|phone|contact|write_access)/u.test(name)) return "04d";
  if (/(popup|scan_qr|qr_|clipboard)/u.test(name)) return "04c";
  if (
    /(invoice|open_link|open_tg_link|share|story|media|prepared_message|send_data|data_send|file_download)/u.test(
      name,
    )
  )
    return "04g";
  if (
    /(iframe_ready|iframe_will_reload|web_app_close|visibility_changed|ready|expand|fullscreen|theme|viewport|safe_area|keyboard|main_button|secondary_button|back_button|settings_button|activated|deactivated|header_color|background_color|bottom_bar_color)/u.test(
      name,
    )
  )
    return "04b";
  return "04h";
}

if (source.schemaVersion !== 1 || !Array.isArray(source.events)) {
  throw new Error("Protocol inventory source is invalid.");
}
if (JSON.stringify(source.profiles) !== JSON.stringify(requiredProfiles)) {
  throw new Error(
    "Protocol inventory profile set differs from the product contract.",
  );
}

const ids = new Set();
const names = new Set();
const events = source.events.map((item) => {
  if (!item || !["outgoing", "incoming"].includes(item.direction)) {
    throw new Error("Protocol inventory event has an invalid direction.");
  }
  if (typeof item.id !== "string" || ids.has(item.id)) {
    throw new Error(`Duplicate or invalid protocol inventory ID: ${item?.id}`);
  }
  const pair = `${item.direction}:${item.name}`;
  if (typeof item.name !== "string" || names.has(pair)) {
    throw new Error(`Duplicate or invalid protocol event: ${pair}`);
  }
  if (typeof item.source !== "string" || !item.source.startsWith("https://")) {
    throw new Error(
      `Protocol event ${item.name} has no HTTPS evidence source.`,
    );
  }
  if (!Array.isArray(item.testIds) || item.testIds.length === 0) {
    throw new Error(`Protocol event ${item.name} has no planned coverage IDs.`);
  }
  ids.add(item.id);
  names.add(pair);
  const profiles = Object.fromEntries(
    requiredProfiles.map((profile) => [
      profile,
      {
        status: "unverified",
        reasonKey: "runtime-qualification-pending",
      },
    ]),
  );
  return {
    id: item.id,
    event: item.name,
    direction: item.direction,
    ownerCard: ownerFor(item.name),
    status: "unverified",
    implemented: false,
    ...(item.minimumVersion ? { minimumVersion: item.minimumVersion } : {}),
    profiles,
    inputSchemaId: `pending:${item.direction}:${item.name}`,
    replyEvents: item.replyEvents ?? [],
    mockPolicy: "unsupported",
    realPolicy: "unsupported",
    testIds: item.testIds,
    sourceIds: [item.source],
  };
});

const outgoing = events.filter((item) => item.direction === "outgoing");
const incoming = events.filter((item) => item.direction === "incoming");
if (outgoing.length !== 64 || incoming.length !== 58) {
  throw new Error(
    `Expected 64 outgoing and 58 incoming events, got ${outgoing.length}/${incoming.length}.`,
  );
}
const countsByOwner = Object.fromEntries(
  ["04b", "04c", "04d", "04e", "04f", "04g", "04h"].map((ownerCard) => [
    ownerCard,
    events.filter((item) => item.ownerCard === ownerCard).length,
  ]),
);

const catalog = {
  schemaVersion: 1,
  sourceGeneratedAt: source.inventoryGeneratedAt,
  sourceSdkSha256: source.sdkSha256,
  sourceEventCount: events.length,
  countsByDirection: { outgoing: outgoing.length, incoming: incoming.length },
  countsByOwner,
  events,
};
const namesFor = (items) => items.map((item) => item.event);
const types =
  `// Generated by scripts/generate-protocol-registry.mjs. Do not edit.\n` +
  `export const OUTGOING_EVENTS = ${JSON.stringify(namesFor(outgoing), null, 2)} as const;\n` +
  `export const INCOMING_EVENTS = ${JSON.stringify(namesFor(incoming), null, 2)} as const;\n` +
  `export type OutgoingEvent = (typeof OUTGOING_EVENTS)[number];\n` +
  `export type IncomingEvent = (typeof INCOMING_EVENTS)[number];\n` +
  `export type TelegramEvent = OutgoingEvent | IncomingEvent;\n` +
  `export function isOutgoingEvent(value: string): value is OutgoingEvent {\n` +
  `  return (OUTGOING_EVENTS as readonly string[]).includes(value);\n` +
  `}\n` +
  `export function isIncomingEvent(value: string): value is IncomingEvent {\n` +
  `  return (INCOMING_EVENTS as readonly string[]).includes(value);\n` +
  `}\n`;
const outputs = new Map([
  [
    join(root, "apps/studio/src/domain/protocol/registry.generated.json"),
    `${JSON.stringify(catalog, null, 2)}\n`,
  ],
  [join(root, "apps/studio/src/domain/protocol/events.generated.ts"), types],
  [
    join(root, "reports/protocol-card-index.json"),
    `${JSON.stringify(
      {
        source: "Telegram Mini Apps WebView event inventory",
        sourceSdkSha256: source.sdkSha256,
        status:
          "inventory assignment only; no protocol method is implemented or platform-verified by this index",
        total: events.length,
        countsByDirection: catalog.countsByDirection,
        countsByOwner: countsByOwner,
        allRowsAssignedExactlyOnce: events.length === ids.size,
        unverifiedRows: events.filter((item) => item.status === "unverified")
          .length,
        implementedRows: events.filter((item) => item.implemented).length,
      },
      null,
      2,
    )}\n`,
  ],
]);

const check = process.argv.includes("--check");
let stale = false;
function equivalentGenerated(path, current, expected) {
  if (path.endsWith(".json")) {
    try {
      return (
        JSON.stringify(JSON.parse(current)) ===
        JSON.stringify(JSON.parse(expected))
      );
    } catch {
      return false;
    }
  }
  const compact = (value) => value.replace(/\s+/gu, "");
  if (compact(current) === compact(expected)) return true;
  const arrayFor = (name, source) => {
    const marker = `export const ${name} = `;
    const start = source.indexOf(marker);
    const arrayStart = source.indexOf("[", start + marker.length);
    const arrayEnd = source.indexOf("] as const;", arrayStart);
    if (start < 0 || arrayStart < 0 || arrayEnd < 0) return null;
    const literals = source
      .slice(arrayStart, arrayEnd)
      .match(/"(?:[^"\\]|\\.)*"/gu);
    return literals?.map((literal) => JSON.parse(literal)) ?? null;
  };
  const outgoingEvents = arrayFor("OUTGOING_EVENTS", current);
  const incomingEvents = arrayFor("INCOMING_EVENTS", current);
  if (outgoingEvents === null || incomingEvents === null) return false;
  const outgoingMatches =
    JSON.stringify(outgoingEvents) === JSON.stringify(namesFor(outgoing));
  const incomingMatches =
    JSON.stringify(incomingEvents) === JSON.stringify(namesFor(incoming));
  if (!outgoingMatches || !incomingMatches) return false;
  const normalized = compact(current);
  return [
    "exporttypeOutgoingEvent=(typeofOUTGOING_EVENTS)[number];",
    "exporttypeIncomingEvent=(typeofINCOMING_EVENTS)[number];",
    "exporttypeTelegramEvent=OutgoingEvent|IncomingEvent;",
    "exportfunctionisOutgoingEvent(value:string):valueisOutgoingEvent{return(OUTGOING_EVENTSasreadonlystring[]).includes(value);}",
    "exportfunctionisIncomingEvent(value:string):valueisIncomingEvent{return(INCOMING_EVENTSasreadonlystring[]).includes(value);}",
  ].every((required) => normalized.includes(required));
}

for (const [path, content] of outputs) {
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (
    current === content ||
    (current !== null && equivalentGenerated(path, current, content))
  )
    continue;
  if (check) {
    console.error(`Generated protocol file is stale: ${path}`);
    stale = true;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`Generated ${path.slice(root.length + 1)}`);
  }
}
if (stale) process.exitCode = 1;
